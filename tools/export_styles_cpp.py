"""Export the Python style library, scales, chord qualities and famous progressions
to C++ so the VST3 plugin and the Python package share one source of truth.

    python tools/export_styles_cpp.py            # rewrites plugin/core/StylesData.inc
    python tools/export_styles_cpp.py --check    # exit 1 if the file is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from melodyverse.progressions import FAMOUS  # noqa: E402
from melodyverse.styles import ALIASES, STYLES  # noqa: E402
from melodyverse.theory import CHORD_QUALITIES, QUALITY_SUFFIX, SCALES  # noqa: E402

OUT = ROOT / "plugin" / "core" / "StylesData.inc"


def q(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def strs(items) -> str:
    return "{" + ", ".join(q(i) for i in items) + "}"


def ints(items) -> str:
    return "{" + ", ".join(str(i) for i in items) + "}"


def render() -> str:
    lines = ["// Generated by tools/export_styles_cpp.py from the Python melodyverse package. Do not edit.", ""]
    lines.append("const std::vector<std::pair<std::string, std::vector<int>>> kScales = {")
    for name, ivs in SCALES.items():
        lines.append(f"    {{{q(name)}, {ints(ivs)}}},")
    lines.append("};\n")
    lines.append("const std::vector<std::tuple<std::string, std::vector<int>, std::string>> kChordQualities = {")
    for name, ivs in CHORD_QUALITIES.items():
        lines.append(f"    {{{q(name)}, {ints(ivs)}, {q(QUALITY_SUFFIX[name])}}},")
    lines.append("};\n")
    lines.append("const std::vector<FamousProgression> kFamous = {")
    for name, (prog, where) in FAMOUS.items():
        lines.append(f"    {{{q(name)}, {q(prog)}, {q(where)}}},")
    lines.append("};\n")
    lines.append("const std::vector<std::pair<std::string, std::string>> kAliases = {")
    for a, b in ALIASES.items():
        lines.append(f"    {{{q(a)}, {q(b)}}},")
    lines.append("};\n")
    lines.append("const std::vector<Style> kStyles = {")
    for st in STYLES.values():
        drums = "{" + ", ".join(f"{{{q(k)}, {q(v)}}}" for k, v in st.drums.items()) + "}"
        steps = "{" + ", ".join(f"{{{k}, {float(v)!r}}}" for k, v in sorted(st.step_weights.items())) + "}"
        inst = st.instruments
        lines.append("    Style{")
        lines.append(f"        {q(st.name)}, {q(st.region)},")
        lines.append(f"        {q(st.description)},")
        lines.append(f"        {q(st.mode)}, {q(st.default_key)}, {st.tempo[0]}, {st.tempo[1]},")
        lines.append(f"        {strs(st.progressions)},")
        lines.append(f"        {strs(st.melody_rhythms)},")
        lines.append(f"        {q(st.chord_pattern)}, {q(st.bass_pattern)},")
        lines.append(f"        {drums},")
        lines.append(f"        {float(st.beats_per_chord)!r}, {q(st.chord_style)},")
        lines.append(f"        {steps},")
        lines.append(f"        {st.melody_range[0]}, {st.melody_range[1]}, {q(st.contour)},")
        lines.append(f"        {strs(st.ornaments)}, {float(st.ornament_rate)!r}, {float(st.swing)!r},")
        lines.append(f"        {q(inst.get('melody', 'piano'))}, {q(inst.get('chords', 'piano'))}, {q(inst.get('bass', 'bass'))},")
        lines.append(f"        {q(st.phrase_form)}, {st.chord_octave}, {strs(st.tags)}")
        lines.append("    },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date; run python tools/export_styles_cpp.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
